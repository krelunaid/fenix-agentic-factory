import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const root = new URL('../templates/web-typescript/', import.meta.url);
const output = new URL('../lib/build-plane/reference-template.generated.ts', import.meta.url);

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue;
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await filesIn(absolute));
    else files.push(absolute);
  }
  return files;
}

const rootPath = root.pathname;
const files = (await filesIn(rootPath)).sort();
const entries = await Promise.all(files.map(async (absolute) => [relative(rootPath, absolute), await readFile(absolute, 'utf8')]));
const source = `// Generated by scripts/generate-reference-template.mjs.\nexport const referenceTemplate = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
await writeFile(output, source);
